    def ident(self, node: Any, in_list: bool = False, depth: int = 0) -> str | None:
        if not isinstance(node, dict) or len(node) < 3:
            return None
        if self.id_key and _id_like(node.get(self.id_key), True):
            return node[self.id_key].strip()
        nested = any(isinstance(v, dict) for v in node.values())
        if not (in_list or depth == 0 or nested):
            return None
        found = _learn_id([node])
        if found and ("id" in str(found).lower() or node[found].strip() in self.rows):
            return node[found].strip()
        return None

    def learn_rows(self, node: list[Any]) -> bool:
        rows = [n for n in node if isinstance(n, dict) and len(n) >= 3]
        if not rows or len(rows) < len(node) / 2:
            return False
        if self.id_key and all(_id_like(r.get(self.id_key), True) for r in rows):
            return True
        found = _learn_id(rows)
        if found:
            self.id_key = found
            return True
        return False

    def absorb(self, observation: Any) -> None:
        def walk(node: Any, depth: int, in_list: bool = False) -> None:
            if depth > 6:
                return
            if isinstance(node, dict):
                ident = self.ident(node, in_list, depth)
                if ident:
                    if in_list and ident not in self.list_keys:
                        self.list_keys[ident] = frozenset(node)
                    if ident not in self.rows:
                        self.seen_order.append(ident)
                        self.rows[ident] = {}
                    old = self.rows[ident]
                    if any(old.get(k) is True and v is False for k, v in node.items()):
                        self.unavailable.add(ident)
                    elif any(old.get(k) is False and v is True for k, v in node.items()):
                        self.unavailable.discard(ident)
                    self.rows[ident].update(node)
                    if _fact_block(node):
                        self.full[ident] = dict(self.rows[ident])
                    elif ident in self.full:
                        self.full[ident].update(node)
                    return
                for value in node.values():
                    walk(value, depth + 1)
            elif isinstance(node, list):
                rows = self.learn_rows(node)
                for value in node:
                    walk(value, depth + 1, rows)

        walk(observation, 0)

    def labels(self) -> set[str]:
        found: set[str] = set()

        def walk(schema: Any, depth: int) -> None:
            if depth > 6 or not isinstance(schema, dict):
                return
            for option in schema.get("enum") or []:
                if isinstance(option, str):
                    found.add(option.strip().lower())
            for value in schema.values():
                if isinstance(value, dict):
                    walk(value, depth + 1)

        for schema in self.schemas.values():
            walk(schema, 0)
        return found

    def category_key(self) -> str | None:
        counts: dict[str, set[str]] = {}
        present: dict[str, int] = {}
        for row in self.rows.values():
            for key, value in row.items():
                named = bool(_key_tokens(key) & CAT_TOKENS)
                if not isinstance(value, str):
                    value = _cat_text(value) if named else None
                size = (len(_cat_leaf(value)) if named else len(value)) if isinstance(value, str) else 0
                if isinstance(value, str) and 0 < size <= 40 and not re.search(r"\d{3}", value):
                    counts.setdefault(key, set()).add(value)
                    present[key] = present.get(key, 0) + 1
        total = max(1, len(self.rows))
        known = self.labels()
        best = None
        for key, values in counts.items():
            if present[key] < 0.8 * total or len(values) > 40:
                continue
            listed = sum(1 for v in values if v.strip().lower() in known) / len(values)
            mean = sum(len(v) for v in values) / len(values)
            score = (-listed, len(values), -present[key], -mean)
            if best is None or score < best[0]:
                best = (score, key)
        return best[1] if best else None

    def key_table(self) -> list[tuple[str, str, int, list[str]]]:
        cat_key = self.category_key()
        groups: dict[str, dict[str, Any]] = {}
        for ident in self.seen_order:
            record = self.full.get(ident)
            if not record:
                continue
            block = _fact_block(record) or {}
            label = (_cat_text(record.get(cat_key)) or "listings") if cat_key else "listings"
            group = groups.setdefault(label, {"n": 0, "keys": {}})
            group["n"] += 1
            done: set[str] = set()
            for key, value in block.items():
                name = _words(key)
                if not name:
                    continue
                text = str(value).strip().lower()
                if name in done:
                    slot = group["keys"][name]
                    if ident in slot["per"] and text and text not in slot["per"][ident]:
                        slot["per"][ident] = slot["per"][ident] + ", " + text
                    if text and text not in slot["values"]:
                        slot["values"].append(text)
                    continue
                done.add(name)
                slot = group["keys"].setdefault(name, {"n": 0, "values": [], "per": {}})
                slot["n"] += 1
                slot["per"][ident] = text
                if text not in slot["values"]:
                    slot["values"].append(text)
        wanted = [(_words(item.shelf or ""), _words(item.name), {w for w in _stem(item.shelf or "") | _stem(item.name) if len(w) >= 4}) for item in self.items]
        matched = {label for label in groups if any(_words(label) in (shelf, name) or {w for w in _stem(label) if len(w) >= 4} & long for shelf, name, long in wanted)}
        if matched:
            groups = {label: group for label, group in groups.items() if label in matched}
        table = []
        for label, group in sorted(groups.items(), key=lambda kv: -kv[1]["n"]):
            kept: list[tuple[str, dict[str, Any]]] = []
            ranked = sorted(
                group["keys"].items(),
                key=lambda kv: (
                    len(kv[1]["values"]) < 2 and kv[1]["n"] >= 2,
                    len(kv[1]["values"]) <= 2 and kv[1]["n"] >= 2 and all(len(v) <= 3 for v in kv[1]["values"]),
                    -kv[1]["n"],
                    len(kv[0].split()),
                ),
            )
            for name, slot in ranked:
                values = list(slot["per"].values())
                if not values or set(name.split()) & TERMS:
                    continue
                mean = sum(len(v) for v in values) / len(values)
                if mean > 40 or sum(1 for v in values if " / " in v) * 2 >= len(values):
                    continue
                if len(values) >= 4 and len(set(values)) == len(values):
                    coded = all(_id_like(v) and len(v.split()) <= 2 for v in values) and mean > 8
                    if mean > 28 or coded:
                        continue
                twin = any(
                    (name.startswith(other + " ") or name.endswith(" " + other))
                    and slot["per"] == spec["per"]
                    for other, spec in kept
                )
                if twin:
                    continue
                kept.append((name, slot))
            for name, slot in kept[:18]:
                table.append((label, name, slot["n"], [v[:40] for v in slot["values"][:4]]))
        return table

    def item_groups(self) -> list[list[str]]:
        cat_key = self.category_key()
        groups: dict[str, list[str]] = {}
        for ident in self.seen_order:
            label = (_cat_text(self.rows[ident].get(cat_key)) or "") if cat_key else ""
            groups.setdefault(label, []).append(ident)
        wanted = [(_words(item.shelf or ""), _words(item.name), {w for w in _stem(item.shelf or "") | _stem(item.name) if len(w) >= 4}) for item in self.items]
        matched = [ids for label, ids in groups.items() if any(_words(label) in (shelf, name) or {w for w in _stem(label) if len(w) >= 4} & long for shelf, name, long in wanted)]
        pool = matched or list(groups.values())
        return sorted(pool, key=lambda ids: -len(ids))[: max(1, len(self.items))]

    def single_target(self, tool: str | None) -> str | None:
        schema = self.schemas.get(tool or "") or {}
        props = schema.get("properties") or {}
        texts = [k for k, v in props.items() if isinstance(v, dict) and "string" in _kinds(v) and "enum" not in v]
        target = next((k for k in schema.get("required") or [] if k in texts), None) or (texts[0] if len(texts) == 1 else None)
        if not tool or not target or any(k != target for k in schema.get("required") or []):
            return None
        return target

    def price_of(self, ident: str) -> float | None:
        row = self.rows.get(ident) or {}
        key = self.price_key or next((k for k in row if set(_words(k).split()) & {"price", "cost"}), None)
        value = row.get(key) if key else None
        if isinstance(value, dict):
            value = next((v for v in value.values() if isinstance(v, (int, float)) and not isinstance(v, bool)), None)
        if isinstance(value, str):
            m = re.fullmatch(r"\s*(?:[$\u20ac\u00a3]|usd|eur|gbp)?\s*(\d{1,3}(?:,\d{3})+|\d+)(\.\d+)?\s*(?:[$\u20ac\u00a3]|usd|eur|gbp|dollars?)?\s*", value, re.I)
            if m:
                value = float(m.group(1).replace(",", "") + (m.group(2) or ""))
        return float(value) if isinstance(value, (int, float)) and not isinstance(value, bool) else None

    def buyable(self, ident: str) -> bool:
        if self.sold_out(ident):
            return False
        row = self.rows.get(ident) or {}
        key = self.stock_key or next((k for k in row if set(_words(k).split()) & {"stock", "available", "availability"}), None)
        value = row.get(key) if key else None
        flip = set(_words(key).split()) if key else set()
        if flip & {"unavailable", "oos"} or ("out" in flip and flip & {"stock", "sold"}):
            if isinstance(value, (int, float)) and not isinstance(value, bool):
                return value <= 0
            return not (value is True or (isinstance(value, str) and re.fullmatch(r"\s*(?:yes|true|y)\s*\.?\s*", value, re.I)))
        if isinstance(value, str) and re.fullmatch(r"\s*(?:no|false|out of stock|sold out|unavailable|not available|agotado|sin stock|no disponible)\s*\.?\s*", value, re.I):
            return False
        return not (value is False or (isinstance(value, (int, float)) and not isinstance(value, bool) and value <= 0))

    def affordable(self, ident: str) -> bool:
        if self.budget is None:
            return True
        price = self.price_of(ident)
        return price is None or price <= self.budget

    def unwrap(self, observation: Any) -> Any:
        if isinstance(observation, dict) and not self.ident(observation):
            if not any(isinstance(v, list) and v and all(isinstance(r, dict) for r in v) for v in observation.values()):
                nested = [v for v in observation.values() if isinstance(v, dict)]
                if len(nested) == 1:
                    return nested[0]
        return observation

    def records_in(self, observation: Any) -> list[tuple[str, dict[str, Any]]]:
        observation = self.unwrap(observation)
        if isinstance(observation, dict):
            ident = self.ident(observation)
            if ident:
                return [(ident, observation)]
            found: list[tuple[str, dict[str, Any]]] = []
            for value in observation.values():
                if isinstance(value, list):
                    found += [(i, r) for r in value if isinstance(r, dict) for i in [self.ident(r, True)] if i]
                elif isinstance(value, dict):
                    found += [(i, r) for v in value.values() if isinstance(v, list) for r in v if isinstance(r, dict) for i in [self.ident(r, True)] if i]
            return found
        if isinstance(observation, list):
            return [(i, r) for r in observation if isinstance(r, dict) for i in [self.ident(r, True)] if i]
        return []

    def note_view(self, name: str, observation: Any) -> None:
        for ident, record in self.records_in(observation):
            keys = set(record)
            self.tool_keys.setdefault(name, set()).update(keys)
            version, have = self.view_keys.get(ident, (-1, set()))
            self.view_keys[ident] = (self.version, (have if version == self.version else set()) | keys)

    def shown_already(self, name: str, ident: str) -> bool:
        version, have = self.view_keys.get(ident, (-1, set()))
        keys = self.tool_keys.get(name)
        return bool(keys) and version == self.version and keys <= have and ident not in self.gone

    def read_shape(self, name: str, observation: Any) -> dict[str, Any] | None:
        if name in self.shapes:
            return self.shapes[name]
        observation = self.unwrap(observation)
        if not isinstance(observation, dict):
            return None
        lists = [k for k, v in observation.items() if isinstance(v, list) and len(v) >= 2 and all(isinstance(r, dict) for r in v)]
        if not lists:
            return None
        self.shapes[name] = None
        sample = {k: (v[:3] if k in lists else v) for k, v in observation.items()}
        prompt = (SHAPE + "\n\nTOOL: " + name + " | parameters: " + _dump(self.schemas.get(name) or {})
                  + "\n\nRESULT (first rows only):\n" + _dump(_clip(sample, 120))[:4000])
        got = self.ask_json(prompt, [LIGHT, HEAVY], 1500) or {}
        rows = got.get("rows") if got.get("rows") in lists else None
        if not rows:
            return None
        first = observation[rows][0]
        props = (self.schemas.get(name) or {}).get("properties") or {}

        def named(key: Any, where: dict[str, Any]) -> str | None:
            return key if isinstance(key, str) and key in where else None

        shape = {"rows": rows, "count": named(got.get("count"), observation), "next": named(got.get("next"), observation),
                 "next_arg": named(got.get("next_arg"), props), "price": named(got.get("price"), first), "stock": named(got.get("stock"), first)}
        if shape["count"] and (isinstance(observation[shape["count"]], bool) or not isinstance(observation[shape["count"]], int)):
            shape["count"] = None
        self.shapes[name] = shape
        self.price_key = self.price_key or shape["price"]
        self.stock_key = self.stock_key or shape["stock"]
        self.trace.append({"kind": "shape", "tool": name, "shape": shape})
        return shape

    def paging(self, name: str, observation: Any) -> tuple[int, int, str, Any] | None:
        observation = self.unwrap(observation)
        shape = self.read_shape(name, observation)
        if not shape or not shape["count"] or not shape["next"] or not shape["next_arg"] or not isinstance(observation, dict):
            return None
        rows, count, value = observation.get(shape["rows"]), observation.get(shape["count"]), observation.get(shape["next"])
        if not isinstance(rows, list) or not rows or isinstance(count, bool) or not isinstance(count, int):
            return None
        if value is not None and (isinstance(value, bool) or not isinstance(value, (str, int))):
            return None
        return count, len(rows), shape["next_arg"], value

    def price_sorted(self, observation: Any) -> bool:
        prices = [self.price_of(i) for i, _ in self.records_in(observation)]
        return len(prices) >= 3 and None not in prices and all(a <= b for a, b in zip(prices, prices[1:]))

    def more_pages(self, name: str, args: dict[str, Any], observation: Any) -> str:
        self.paged_obs = []
        pick = self.brief.get("pick")
        plan = self.paging(name, observation) if pick in ("cheapest", "most", "least") else None
        if not plan:
            return ""
        count, shown, param, value = plan
        given = args.get(param)
        later = given not in (None, 0, 1) if isinstance(given, int) and not isinstance(given, bool) else bool(str(given or "").strip())
        if value is None or later or count <= shown:
            return ""
        if pick == "cheapest" and self.price_sorted(observation):
            return ""
        pages = -(-(count - shown) // shown)
        if pages > 2 or self.pages_read + pages > AUTO_PAGES or self.left() - self.tail() - pages < 12:
            return (f"\n[Kyo] This search matched {count} listings and showed {shown}, in no price order. The pick counts every fitting listing: "
                    f"search with narrower words (the requirement's value) or page on with {param}={_dump(value)}.")
        texts = []
        for _ in range(pages):
            faults: list[str] = []
            call = _shape({**args, param: value}, self.schemas.get(name), "args", faults)
            if faults:
                break
            reply = self.act(name, call)
            if reply is None or self.finished:
                break
            self.pages_read += 1
            seen = reply.get("observation")
            self.observe(name, seen)
            self.paged_obs.append(seen)
            shown_text = self.show(seen)
            self.read_cache[name + _dump(call)] = (self.version, self.step, shown_text)
            texts.append(f"{param}={_dump(value)}: {shown_text}")
            after = self.paging(name, seen)
            value = after[3] if after else None
            if value is None:
                break
        self.trace.append({"kind": "pages", "tool": name, "read": len(texts)})
        return ("\n[Kyo read the rest of this search itself, one step a page]\n" + "\n".join(texts)) if texts else ""

    def cheapest_here(self, observations: list[Any]) -> str:
        if self.brief.get("pick") != "cheapest" or not self.price_key:
            return ""
        found = {i for seen in observations for i, _ in self.records_in(seen)}
        rows = [(self.price_of(i), i) for i in found if self.buyable(i) and self.price_of(i) is not None]
        if len(rows) < 2:
            return ""
        return "\n[Kyo] buyable rows here, cheapest first: " + ", ".join(f"{i} ({p:g})" for p, i in sorted(rows)[:6])

    def wider_hold(self) -> str:
        if self.wider_held or self.brief.get("pick") != "cheapest" or self.left() < 14 + 2 * len(self.items):
            return ""
        self.wider_held = True
        lines = [f"{i} at {self.price_of(i):g}" for i in self.cart_ids() if self.price_of(i) is not None]
        return (f"Not run yet (no step used). {self.left()} steps are left and the pick is the cheapest. Searches miss many fitting listings"
                " and rows come in no price order."
                " Before checking out, run a few more searches for each item under other names for the product (its plain one-word name,"
                " synonyms, words from fitting titles you have seen) and look only at buyable rows priced below the cart's line"
                + (f" ({'; '.join(lines)})" if lines else "") + "; read the attributes of the cheapest such rows, swap in any that fits, then check out.")

    def fill_facts(self, ids: list[str], keep: int) -> list[str]:
        tool = self.facts_tool()
        target = self.single_target(tool)
        if not tool or not target:
            return []
        texts = []
        for ident in [i for i in ids if i in self.rows and i not in self.full and not self.sold_out(i)]:
            if self.left() <= keep or self.finished or self.facts_from.get(tool) is False:
                break
            faults: list[str] = []
            args = _shape({target: ident}, self.schemas.get(tool), "args", faults)
            if faults:
                break
            reply = self.act(tool, args)
            if reply is None:
                break
            seen = reply.get("observation")
            self.observe(tool, seen)
            self.note_view(tool, seen)
            inner = self.unwrap(seen)
            if isinstance(inner, dict) and self.ident(inner):
                self.facts_from[tool] = self.facts_from.get(tool, False) or bool(_fact_block(inner))
            texts.append(f"{ident}: " + self.show(seen)[:1500])
        if texts:
            self.trace.append({"kind": "fill_facts", "n": len(texts)})
        return texts

    def cheaper_rows(self) -> list[str]:
        if self.brief.get("pick") != "cheapest":
            return []
        mark = self.cart_mark() + f"#{self.version}"
        cat_key = self.category_key()
        if mark in self.cheaper_marks or not cat_key:
            return []
        self.cheaper_marks.add(mark)
        cart = self.cart_ids()
        picks: list[str] = []
        for line in cart:
            price = self.price_of(line)
            kind = (_cat_text((self.rows.get(line) or {}).get(cat_key)) or "").strip().lower()
            if price is None or not kind:
                continue
            pool = [i for i in self.seen_order if i not in cart and i not in self.full and self.buyable(i)
                    and (_cat_text((self.rows.get(i) or {}).get(cat_key)) or "").strip().lower() == kind
                    and (self.price_of(i) if self.price_of(i) is not None else float("inf")) < price]
            pool.sort(key=lambda i: self.price_of(i) or 0.0)
            picks += [i for i in pool[:2] if i not in picks]
        return self.fill_facts(picks[:CHEAPER_OPENS], self.tail() + 4)

    def observe(self, name: str, observation: Any) -> str:
        self.absorb(observation)
        lines = self.loose_lines(observation)
        if not lines:
            return ""
        meaning = self.take_note(lines)
        if meaning:
            self.queued.append(f"(seen on {name}) {meaning}")
        return meaning

    def heading(self, ident: str) -> str:
        row = self.rows.get(ident) or {}
        texts = [
            _words(v)
            for k, v in row.items()
            if k != self.id_key and isinstance(v, str) and not _id_like(v, True) and len(_words(v).split()) >= 2
        ]
        title = max(texts, key=len) if texts else ""
        head = " ".join(title.split()[:3])
        return head if head else ident

    def spread(self, pool: list[str], seen: list[str], limit: int) -> list[str]:
        heads = {self.heading(i) for i in seen}
        fresh: list[str] = []
        rest: list[str] = []
        for ident in pool:
            head = self.heading(ident)
            if head not in heads:
                heads.add(head)
                fresh.append(ident)
            else:
                rest.append(ident)
        return (fresh + rest)[:limit]

    def advance(self) -> None:
        if not self.searched or self.left() <= 16:
            return
        opened = {self.heading(i) for i in self.full if self.affordable(i)}
        unseen = {self.heading(i) for i in self.rows if i not in self.full and self.buyable(i) and self.affordable(i)} - opened
        if len(opened) + len(unseen) >= min(6, 3 * len(self.items) + 1) and len(unseen) >= 2:
            return
        name, args, obs = self.searched
        plan = self.paging(name, obs)
        if not plan:
            return
        count, shown, param, value = plan
        if value is None or count <= shown:
            return
        faults: list[str] = []
        call = _shape({**args, param: value}, self.schemas.get(name), "args", faults)
        if faults:
            return
        reply = self.act(name, call)
        if reply is None or self.finished:
            return
        self.pages_read += 1
        seen = reply.get("observation")
        self.observe(name, seen)
        self.searched = (name, call, seen)
        self.read_cache[name + _dump(call)] = (self.version, self.step, self.show(seen))

    def widen(self) -> None:
        self.advance()
        tool = self.roles.get("compare")
        schema = self.schemas.get(tool or "") or {}
        props = schema.get("properties") or {}
        target = next((k for k, v in props.items() if isinstance(v, dict) and "array" in _kinds(v)), None)
        if not tool or not target or any(k != target for k in schema.get("required") or []) or self.compare_bare():
            self.widen_singly()
            return
        if self.left() <= 12:
            return
        cap = props[target].get("maxItems") if isinstance(props[target].get("maxItems"), int) else 4
        ranked = self.item_groups()
        share = max(1, cap // max(1, len(ranked)))
        picks: list[str] = []
        for ids in ranked:
            pool = ([i for i in ids if i not in self.full and self.buyable(i) and self.affordable(i)]
                    or [i for i in ids if i not in self.full and self.buyable(i)]
                    or [i for i in ids if i not in self.full])
            picks += self.spread(pool, [i for i in ids if i in self.full], share)
        if len(picks) < cap:
            for ids in ranked:
                pool = ([i for i in ids if i not in self.full and i not in picks and self.buyable(i) and self.affordable(i)]
                        or [i for i in ids if i not in self.full and i not in picks and self.buyable(i)])
                picks += self.spread(pool, [i for i in ids if i in self.full] + picks, cap - len(picks))
        picks = picks[:cap]
        if len(picks) < 2:
            return
        faults: list[str] = []
        args = _shape({target: picks}, schema, "args", faults)
        if faults:
            return
        before = len(self.full)
        reply = self.act(tool, args)
        if reply is not None:
            seen = reply.get("observation")
            self.observe(tool, seen)
            self.note_view(tool, seen)
            rows = self.records_in(seen)
            if rows:
                self.facts_from[tool] = self.facts_from.get(tool, False) or any(_fact_block(r) for _, r in rows)
            self.trace.append({"kind": "widen", "ids": picks, "opened": len(self.full) - before})
            if rows and self.facts_from.get(tool) is False:
                self.widen_singly()
                return
            if len(self.full) == before and len(picks) > 2 and self.left() > 12:
                faults = []
                args = _shape({target: picks[:2]}, schema, "args", faults)
                if not faults:
                    reply = self.act(tool, args)
                    if reply is not None:
                        self.observe(tool, reply.get("observation"))

    def widen_singly(self) -> None:
        tool = self.facts_tool()
        target = self.single_target(tool)
        if not tool or not target:
            return
        lanes: list[list[str]] = []
        for ids in self.item_groups():
            opened = [i for i in ids if i in self.full]
            pool = ([i for i in ids if i not in self.full and self.buyable(i) and self.affordable(i)]
                    or [i for i in ids if i not in self.full and self.buyable(i)])
            if self.brief.get("pick") == "cheapest":
                pool.sort(key=lambda i: self.price_of(i) if self.price_of(i) is not None else float("inf"))
            lanes.append(self.spread(pool, opened, max(0, min(2, 8 - len(opened)))))
        queue = [lane[k] for k in range(2) for lane in lanes if k < len(lane)]
        self.fill_facts(queue[:5], 22)

    def fit_fault(self) -> str:
        ids = self.cart_ids()
        cart = tuple(sorted(ids))
        if len(ids) < 2 or cart in self.fit_carts or len(self.fit_carts) >= 2 or self.left() <= self.order_room() + 2:
            return ""
        record = lambda i: {**(self.rows.get(i) or {}), **(self.full.get(i) or {})}
        marks = {i: _family(_dump(record(i))) for i in ids}
        hosts = {code for models, _ in marks.values() for code in models} | {c.replace("-", "") for c in re.findall(CODE, self.request)}
        stems = {_series(code) for code in hosts}
        wrong = [i for i, (models, named) in marks.items() if not models and {c for c in named if _series(c) in stems} and not named & hosts]
        if not wrong:
            return ""
        self.fit_carts.add(cart)
        cat_key = self.category_key()
        said = []
        for ident in wrong:
            shelf = (_cat_text(record(ident).get(cat_key)) or "") if cat_key else ""
            rows = [i for i in self.rows if i not in ids and not self.sold_out(i) and (not shelf or (_cat_text(record(i).get(cat_key)) or "") == shelf) and _family(_dump(record(i)))[1] & hosts]
            rows.sort(key=lambda i: self.price_of(i) if self.price_of(i) is not None else float("inf"))
            said.append(f"{ident} names {', '.join(sorted(c for c in marks[ident][1] if _series(c) in stems))}" + (f"; seen on its shelf naming the device: {', '.join(rows[:5])}" if rows else ""))
        self.trace.append({"kind": "fit_hold", "hosts": sorted(hosts), "wrong": wrong})
        return f"Lines in this cart name other models than the device in it (model {', '.join(sorted(hosts))}): " + "; ".join(said) + ". When the request wants these items to go with that device, swap each such line for one whose description names the device, or switch the device; model codes sit only in the descriptions, so read the rows by browsing that shelf, a keyword search does not find them. When the request does not tie them together, check out as it is."

    def fitted_items(self) -> set[int]:
        cat_key = self.category_key()
        if not cat_key or len(self.items) < 2:
            return set()
        texts: dict[int, list[str]] = {}
        for record in self.full.values():
            number = self.shelf_of(_cat_text(record.get(cat_key)) or "")
            if number:
                texts.setdefault(number, []).append(_dump(record))
        made = {n: {m for text in rows for m in MADE.findall(text)} for n, rows in texts.items()}
        fitted: set[int] = set()
        for number, rows in texts.items():
            hosts = {m for other, marks in made.items() if other != number for m in marks}
            if sum(1 for text in rows if set(FITS.findall(text)) & hosts) * 2 >= len(rows):
                fitted.add(number)
        return fitted

    def ready_to_ask(self) -> bool:
        if self.asked or not self.roles.get("ask") or self.msgs_free() <= 0:
            return False
        if self.left() <= 8:
            return False
        opened = len(self.full)
        if opened >= 3 * len(self.items) + 1:
            return True
        return self.step >= max(8, self.max_steps // 4)

    def message_args(self, text: str) -> dict[str, Any] | None:
        name = self.roles.get("ask")
        schema = self.schemas.get(name or "") or {}
        props = schema.get("properties") or {}
        texts = [k for k, v in props.items() if isinstance(v, dict) and "string" in _kinds(v) and "enum" not in v]
        target = next((k for k in schema.get("required") or [] if k in texts), None) or (texts[0] if texts else None)
        if not target:
            return None
        args: dict[str, Any] = {target: text}
        for key in schema.get("required") or []:
            if key not in args:
                spec = props.get(key) or {}
                if isinstance(spec.get("enum"), list) and spec["enum"]:
                    args[key] = spec["enum"][0]
                else:
                    return None
        faults: list[str] = []
        args = _shape(args, schema, "args", faults)
        return None if faults else args

    def interview(self) -> str:
        self.asked = True
        count = self.msgs_free()
        if count <= 0:
            return ""
        self.widen()
        if len(self.full) < min(8, 3 * len(self.items) + 1) and self.left() > 16:
            self.widen()
        table = self.key_table()
        settled = []
        for number, item in enumerate(self.items, 1):
            settled.append(f"item {number}: {item.name} - settled by the request: " + ("; ".join(item.musts) or "nothing"))
        listing = []
        last = None
        for index, (label, name, carried, values) in enumerate(table, 1):
            if label != last:
                listing.append(f"category {label!r}:")
                last = label
