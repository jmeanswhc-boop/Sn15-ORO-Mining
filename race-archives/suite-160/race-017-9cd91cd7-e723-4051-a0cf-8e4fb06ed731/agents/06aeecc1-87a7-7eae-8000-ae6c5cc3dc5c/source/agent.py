def _key_tokens(key: Any) -> set[str]:
    spaced = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1 \2", str(key))
    spaced = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", spaced)
    tokens = {w for w in re.split(r"[^a-z0-9]+", spaced.lower()) if w}
    return tokens | {w[:-1] for w in tokens if len(w) > 3 and w.endswith("s")}


def _object_like(fields: Any) -> bool:
    names = {str(k).strip().lower() for k in fields}
    return bool(names) and names <= OBJ_META | OBJ_PLAIN and bool(names & OBJ_META)


def _fact_block(node: Any) -> dict[str, Any] | None:
    if not isinstance(node, dict):
        return None
    best = None
    for key, value in node.items():
        if isinstance(value, dict) and len(value) >= 2:
            scalars = {k: v for k, v in value.items() if isinstance(v, (str, int, float)) and not isinstance(v, bool)}
            if len(scalars) < 2:
                continue
            meta = bool(_key_tokens(key) & (META_TOKENS | CAT_TOKENS))
            plain = _object_like(scalars)
            if (meta and plain) if FACTS_STRONG.search(str(key)) else (meta or plain):
                continue
            if best is None or len(scalars) > len(best):
                best = scalars
    return best


def _cat_text(value: Any, depth: int = 0) -> str | None:
    if depth > 3:
        return None
    if isinstance(value, str):
        return value
    if isinstance(value, dict):
        for name in ("path", "breadcrumb", "breadcrumbs", "full_name", "name", "label", "title", "value", "display", "text"):
            got = value.get(name)
            if isinstance(got, (str, list, dict)) and got:
                parsed = _cat_text(got, depth + 1)
                if parsed is not None and parsed.strip():
                    return parsed.strip()
        return None
    if isinstance(value, list) and value and all(isinstance(x, str) for x in value):
        texts = [x.strip() for x in value if x.strip()]
        return " > ".join(texts) if texts else None
    return None


