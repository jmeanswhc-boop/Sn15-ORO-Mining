FACTS_NAME = re.compile(r"fact|spec|attribute|trait|propert|detail|feature|characteristic", re.I)
PAIR_NAMES = ("name", "key", "label", "attribute", "property", "field")
PAIR_VALUES = ("value", "val", "text", "detail", "values")
PAIR_UNITS = ("unit", "units", "uom")
PAIR_TEXT = re.compile(r"^\s*([A-Za-z_][\w /.\-]{0,40}?)\s*[=:]\s*(.+?)\s*$", re.S)


def _pair_value(x: dict[str, Any]) -> Any:
    vals = [x[n] for n in x if str(n).lower() in PAIR_VALUES and isinstance(x[n], (str, int, float)) and not isinstance(x[n], bool)]
    units = [x[n] for n in x if str(n).lower() in PAIR_UNITS and isinstance(x[n], str) and x[n].strip()]
    used = sum(1 for n in x if str(n).lower() in PAIR_VALUES + PAIR_UNITS)
    if len(vals) != 1 or len(units) > 1 or used != len(vals) + len(units):
        return None
    return (vals, units, used)


def _pairs_block(key: Any, value: Any) -> dict[str, Any] | None:
    if not FACTS_NAME.search(str(key)):
        return None
    out: dict[str, Any] = {}

    def put(name: str, val: Any, units: list[str]) -> None:
        val = f"{val} {units[0].strip()}" if units else val
        out[name] = f"{out[name]}, {val}" if name in out else val

    if isinstance(value, list) and len(value) >= 2:
        if all(isinstance(x, dict) for x in value):
            for x in value:
                names = [x[n] for n in x if str(n).lower() in PAIR_NAMES and isinstance(x[n], str) and x[n].strip()]
                got = _pair_value(x)
                if len(names) != 1 or not got or len(x) != 1 + got[2]:
                    return None
                put(names[0].strip(), got[0][0], got[1])
            return out if len(out) >= 2 else None
        if all(isinstance(x, str) for x in value):
            for part in value:
                m = PAIR_TEXT.match(part)
                if not m:
                    return None
                put(m.group(1).strip(), _scalar(m.group(2)), [])
            return out if len(out) >= 2 else None
        return None
    if isinstance(value, str) and ("=" in value or ":" in value):
        for sep in ("; ", ";", ", "):
            parts = [p for p in value.split(sep) if p.strip()]
            got = [PAIR_TEXT.match(p) for p in parts]
            if len(parts) >= 2 and all(got):
                for m in got:
                    put(m.group(1).strip(), _scalar(m.group(2)), [])
                return out if len(out) >= 2 else None
        return None
    if isinstance(value, dict) and len(value) >= 2 and all(isinstance(x, dict) for x in value.values()):
        for name, x in value.items():
            got = _pair_value(x)
            if not got or len(x) != got[2]:
                return None
            put(str(name), got[0][0], got[1])
        return out
    return None


def _scalar(text: str) -> Any:
    value = text.strip()
    if value in ("None", "null", "none", ""):
        return None
    if value in ("True", "true"):
        return True
    if value in ("False", "false"):
        return False
    if re.fullmatch(r"-?\d{1,15}", value):
        return int(value)
    if re.fullmatch(r"-?\d{1,15}\.\d+", value):
        return float(value)
    return value


def _sub_record(text: str) -> dict[str, Any] | None:
    for mark in ("=", ":"):
        pair = re.compile(r"^\s*([A-Za-z_][\w /.\-]{0,40}?)\s*" + mark + r"\s*(.*)$", re.S)
        found: dict[str, dict[str, str]] = {}
        for sep in ("; ", ";", ", "):
            parts = [p for p in text.split(sep) if p.strip()]
            out: dict[str, Any] = {}
            keyed = 0
            for part in parts:
                m = pair.match(part)
                if m and m.group(1).strip() not in out:
                    keyed += 1
                    out[m.group(1).strip()] = m.group(2)
                elif out:
                    last = next(reversed(out))
                    out[last] = out[last] + sep + part
            if keyed >= (2 if mark == ":" or len(parts) > 1 else 1) and (keyed == len(parts) if mark == ":" else keyed * 2 >= len(parts)):
                found.setdefault(sep, out)
        pick = (next((found[s] for s in ("; ", ";", ", ") if s in found and len(found[s]) >= 2), None)
                or next((found[s] for s in ("; ", ";", ", ") if s in found), None))
        if pick:
            return {k: _scalar(v) for k, v in pick.items()}
    return None


def _named_id(record: dict[str, Any]) -> str | None:
    for key, value in record.items():
        if isinstance(value, str) and _id_like(value) and re.search(r"(?:id|ref|code|sku|number|key)\b|^(?:id|ref|code|sku)", str(key), re.I):
            return key
    return None


def _id_key_of(record: dict[str, Any]) -> str | None:
    named = _named_id(record)
    if named:
        return named
    first = next(iter(record), None)
    return first if first is not None and _id_like(record[first]) else None


def _line_records(text: str) -> list[dict[str, Any]] | None:
    if "\n" not in text:
        return None
    lines = [line for line in text.splitlines() if line.strip()]
    if len(lines) < 2:
        return None
    got = [r for r in (_text_record(line) for line in lines) if r]
    return got if len(got) >= 2 and len(got) * 2 >= len(lines) else None


def _decoded(text: str) -> Any:
    bare = text.strip()
    if bare[:1] in "{[" and bare[-1:] in "}]":
        try:
            inner = json.loads(bare)
        except (ValueError, RecursionError):
            inner = None
        if isinstance(inner, (dict, list)):
            return inner
    return _line_records(text) or _text_record(text) or text


def _text_record(text: Any) -> dict[str, Any] | None:
    if not isinstance(text, str) or len(text) < 24:
        return None
    for sep in (" | ", "\n", " ; ", " || "):
        parts = [p for p in text.split(sep) if p.strip()]
        if len(parts) < 3:
            continue
        head = re.match(r"^\s*([A-Za-z_][\w ]{0,40}?)\s*([:=])", parts[0])
        if not head or len(head.group(1).strip()) < 2:
            continue
        word = r"[\w ]{0,40}?" if " " in head.group(1).strip() else r"\w{0,40}"
        line = re.compile(r"^\s*([A-Za-z_]" + word + r")\s*" + head.group(2) + r"\s?(.*)$", re.S)
        raws: dict[str, str] = {}
        keyed = 0
        for part in parts:
            m = line.match(part)
            if not m or m.group(1) in raws:
                if raws:
                    last = next(reversed(raws))
                    raws[last] = raws[last] + sep + part
                continue
            keyed += 1
            raws[m.group(1)] = m.group(2)
        out: dict[str, Any] = {}
        for key, raw in raws.items():
            sub = _sub_record(raw) if ("=" in raw or ":" in raw) and key.strip().lower() not in ("title", "name", "item_blurb", "description") else None
            out[key] = sub if sub else _scalar(raw)
        if keyed >= 3 and keyed * 2 >= len(parts) and _id_key_of(out):
            return out
    return None


