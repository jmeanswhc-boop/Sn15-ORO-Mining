def _blocks(pool: list[str], own: frozenset[str]) -> list[list[str]]:
    out: list[list[str]] = []
    cores: list[frozenset[str]] = []
    for lab in pool:
        c = _core(lab, own)
        spot = next((i for i, o in enumerate(cores) if c & o), None)
        if spot is None:
            out.append([lab])
            cores.append(c)
        else:
            out[spot].append(lab)
    return out


