        lanes: dict[int, list[tuple[int, str]]] = {}
        for number in range(1, len(self.items) + 1):
            item = self.items[number - 1]
            shelf, title = _words(item.shelf or ""), _words(item.name)
            stems = {w for w in _stem(item.shelf or "") | _stem(item.name) if len(w) >= 4}
            joined = " ".join(m.split(":")[0] for m in item.musts).lower()
            keys = [
                name
                for label, name, _, _ in table
                if _words(label) in (shelf, title) or ({w for w in _stem(label) if len(w) >= 4} & stems)
            ]
            if not keys and len(self.items) == 1:
                keys = [name for _, name, _, _ in table]
            picks = grouped.get(number, [])
            if len(keys) >= 3:
                kept: list[tuple[int, str]] = []
                unlisted = 0
                for n, lab, hinted in picks:
                    stem = _stem(lab)
                    if any(stem & _stem(k) for k in keys):
                        kept.append((n, lab))
                    elif hinted and unlisted < 1:
                        unlisted += 1
                        kept.append((n, lab))
            else:
                kept = [(n, lab) for n, lab, _ in picks]
            for k in keys:
                if len(kept) >= count + 1:
                    break
                if k not in joined and all(
                    _words(k) != _words(other) and not (_stem(k) <= _stem(other)) and not (_stem(other) <= _stem(k))
                    for _, other in kept
                ):
                    kept.append((number, k))
            if kept:
                if number not in order:
                    order.append(number)
                lanes[number] = kept
        ordered: list[tuple[int, str]] = []
        fitted = self.fitted_items()
        for group in ([n for n in order if n not in fitted], [n for n in order if n in fitted]):
            span = max((len(lanes.get(n, ())) for n in group), default=0)
