        self.trace.append({"kind": "plan", "ask": _clip(plan.get("ask"), 120)})
        sent: list[tuple[int, str, str]] = []
        told: list[str] = []
        pools = {n: self.net_pool(n, lanes.get(n, []), table) for n in range(1, len(self.items) + 1)}
        nets = {n: 0 for n in pools}
        ahead = {n: True for n in pools}
        misses = {n: 0 for n in pools}
        found: set[int] = set()
        crowded = False
        singles = [(n, lab) for n, lab in ordered if not self.settled_label(n, lab)]
        asked: set[tuple[int, str]] = set()
        leads: dict[int, set[str]] = {}
        ranked = [n for n in order if n not in fitted] + [n for n in order if n in fitted]
        ranked += [n for n in pools if n not in ranked]
        while self.msgs_free() > 0:
            choice = None
            if not crowded:
                live = [n for n in ranked if len(pools[n]) >= 2]
                open_items = [n for n in live if n not in found]
