def _family(text: str) -> tuple[set[str], set[str]]:
    models = {c.replace("-", "") for c in MODEL.findall(text)}
    named: set[str] = set()
    for hit in CODES.finditer(text):
        lead = re.split(r'[.;!]\s|","|":"|\n', text[max(0, hit.start() - 40):hit.start()])[-1]
        if not OTHER.search(lead):
            named |= {c.replace("-", "") for c in re.findall(CODE, hit.group(0))}
    return models, named - models


def _series(code: str) -> str:
    return re.sub(r"\d", "", code)


def _dump(value: Any) -> str:
    try:
        return json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    except (TypeError, ValueError):
        return str(value)


def _clip(value: Any, limit: int, depth: int = 0) -> Any:
    if depth > 7:
        return "..."
    if isinstance(value, str):
        return value if len(value) <= limit else value[:limit] + "..."
    if isinstance(value, dict):
        return {k: _clip(v, limit, depth + 1) for k, v in value.items()}
    if isinstance(value, list):
        return [_clip(v, limit, depth + 1) for v in value]
    return value


def _json_obj(text: Any) -> dict[str, Any] | None:
    if not isinstance(text, str):
        return None
    text = text.strip()
    fence = re.match(r"^```[A-Za-z]*\s*(.*?)\s*```$", text, re.S)
    if fence:
        text = fence.group(1)
    try:
        got = json.loads(text)
        return got if isinstance(got, dict) else None
    except ValueError:
        pass
    left, right = text.find("{"), text.rfind("}")
    if 0 <= left < right:
        try:
            got = json.loads(text[left:right + 1])
            return got if isinstance(got, dict) else None
        except ValueError:
            return None
    return None


def _words(key: str) -> str:
    key = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", str(key))
    return re.sub(r"[\s_.\-]+", " ", key).strip().lower()


def _stem(text: str) -> frozenset[str]:
    return frozenset(w[:-1] if len(w) > 3 and w.endswith("s") else w for w in _words(text).split())


def _near(one: str, two: str) -> bool:
    left, right = sorted((_stem(one), _stem(two)), key=len)
    if not left or "".join(_words(one).split()) == "".join(_words(two).split()):
        return bool(left)
    if len(left) != len(right):
        return False
    return all(any(a[:3] == b[:3] and (a.startswith(b) or b.startswith(a)) for b in right) for a in left)


