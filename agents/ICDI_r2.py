    def think(self, messages: list[dict[str, Any]], models: list[str], max_tokens: int, tools: list[dict[str, Any]] | None = None) -> dict[str, Any] | None:
        for model in models:
            tries = 0
            while not self.no_credit and not self.budget_breached and self.calls < ALL_CALLS:
                message, status = self.call_model(model, messages, max_tokens, tools)
                if message is not None:
                    return message
                if status == 402:
                    self.no_credit = True
                    return None
                retryable = status is None or status in (408, 425, 429) or (isinstance(status, int) and status >= 500)
                if not retryable or tries >= 1 or self.waited + WAITS[tries] > WAIT_TOTAL:
                    break
                pause = WAITS[tries] * (0.8 + 0.4 * random.random())
                self.waited += WAITS[tries]
                tries += 1
                time.sleep(pause)
        return None

    def quote_inference(self, body: dict[str, Any]) -> tuple[float, int, int] | None:
        rates = INFERENCE_RATES.get(body.get("model"))
        maximum = body.get("max_tokens")
        if not rates or not isinstance(maximum, int) or isinstance(maximum, bool) or maximum <= 0:
            return None
        prompt = len(_dump(body).encode("utf-8")) + 1024 + 64 * len(body.get("messages") or []) + 128 * len(body.get("tools") or [])
        applicable = [r for r in rates if r[0] <= prompt]
        input_rate = max(r[1] for r in applicable)
        output_rate = max(r[2] for r in applicable)
        available = max(0.0, EPISODE_USD - self.cost - (0 if self.in_recovery else FINISH_USD))
        base = prompt * input_rate
        cap = min(maximum, max(0, int((available / 1.25 - base) / output_rate)))
        if cap < min(maximum, 1024):
            return None
        reserved = 1.25 * (base + cap * output_rate)
        return (reserved, cap, prompt) if reserved <= available + 1e-12 else None

    def call_model(self, model: str, messages: list[dict[str, Any]], max_tokens: int, tools: list[dict[str, Any]] | None) -> tuple[dict[str, Any] | None, Any]:
        sent = messages
        if model.startswith("anthropic/") and len(messages) > 1:
            sent = [dict(m) for m in messages]
            for index in (0, len(sent) - 1):
                content = sent[index].get("content")
                if isinstance(content, str) and content:
                    sent[index]["content"] = [{"type": "text", "text": content, "cache_control": {"type": "ephemeral"}}]
        body: dict[str, Any] = {"model": model, "messages": sent, "max_tokens": max_tokens, "temperature": 0}
        if tools:
            body["tools"] = tools
            body["tool_choice"] = "auto"
        quote = self.quote_inference(body)
        if self.no_credit or self.budget_breached or self.calls >= ALL_CALLS or quote is None:
            self.trace.append({"kind": "budget_denied", "model": model, "spent": self.cost})
            return None, "budget_denied"
        reserved, body["max_tokens"], prompt_bound = quote
        self.calls += 1
        self.cost += reserved
        try:
            result = _llm.post_verbose("/inference/chat/completions", body)
            data = result.data
            error = result.error if isinstance(result.error, dict) else {}
        except Exception:
            data, error = None, {"status": None}
        usage = data.get("usage") if isinstance(data, dict) else None
        reported = usage.get("cost") if isinstance(usage, dict) else None
        if isinstance(reported, (int, float)) and not isinstance(reported, bool) and 0 <= reported < float("inf"):
            self.cost = max(0.0, self.cost - reserved) + reported
            self.budget_breached = reported > reserved + 1e-12
        else:
            reported = None
        if isinstance(usage, dict):
            for field, bound in (("prompt_tokens", prompt_bound), ("completion_tokens", body["max_tokens"])):
                count = usage.get(field)
                if isinstance(count, (int, float)) and not isinstance(count, bool) and count > bound:
                    self.budget_breached = True
        self.trace.append({"kind": "inference_budget", "model": model, "attempt": self.calls,
                           "reserved": reserved, "reported": reported, "accounted": self.cost,
                           "output_limit": body["max_tokens"], "breached": self.budget_breached})
        if isinstance(data, dict) and isinstance(data.get("choices"), list) and data["choices"]:
            first = data["choices"][0]
            message = first.get("message") if isinstance(first, dict) else None
            if isinstance(message, dict) and (message.get("content") or message.get("tool_calls")):
                return message, 200
            return None, 0
        status = error.get("status")
        if isinstance(data, dict) and isinstance(data.get("error"), dict):
            status = _count(data["error"].get("code"))
        if status == 402:
            self.no_credit = True
        self.trace.append({"kind": "llm_fail", "model": model, "status": status})
        return None, status

    def ask_json(self, prompt: str, models: list[str], max_tokens: int = 1800) -> dict[str, Any] | None:
        for model in models:
            message = self.think([{"role": "user", "content": prompt}], [model], max_tokens)
            got = _json_obj((message or {}).get("content"))
            if got is not None:
                return got
            if self.broke or self.no_credit or self.calls >= ALL_CALLS:
                return None
        return None

    def act(self, name: str, args: dict[str, Any]) -> dict[str, Any] | None:
        self.action_hold = ""
        if self.finished or self.left() <= 0:
            return None
        if not self.in_gate and name == self.roles.get("cart") and self.gate_due("choose"):
            go, reason = self.gate("choose")
            if not go:
                self.action_hold = reason
                return None
        stage = "order" if self.is_buy(name, args) else "end" if self.is_refuse(name, args) else ""
        if stage:
            if self.pending_notes or self.pending_answers or (stage == "order" and self.unclear):
                self.action_hold = "Resolve the outstanding observations or ambiguous instructions before ending."
                self.trace.append({"kind": "finish_held", "reason": "unresolved observations or instructions"})
                return None
            go, reason = self.gate(stage)
            if not go:
                self.action_hold = reason
                return None
            if stage == "order":
                self.action_hold = self.check_cart(limit=SPEND_HARD)
                if self.action_hold:
                    return None
        if self.finished or self.left() <= 0:
            return None
        payload = dict(self.binding)
        payload["step"] = self.step + 1
        payload["action"] = {"name": name, "args": args}
        for _ in range(4):
            result = _env.post_verbose("/environment/call", payload)
            if isinstance(result.data, dict):
                data = dict(result.data)
                data["observation"] = _observation(data.get("observation"))
                self.step = data["step"] if isinstance(data.get("step"), int) else self.step + 1
                if data.get("finished"):
                    self.finished = True
                seen = data.get("observation")
                if name in self.page_tools() and not (isinstance(seen, dict) and seen.get("error")):
                    # listings whose full page the agent has opened (a search row is not that)
                    for value in args.values():
                        self.opened.update(v.strip() for v in (value if isinstance(value, list) else [value]) if isinstance(v, str))
                return data
            error = result.error or {}
            status = error.get("status")
            body = str(error.get("body") or "")
            self.trace.append({"kind": "env_fail", "status": status, "body": body[:200]})
            if status == 409:
                low = body.lower()
                if "finish" in low or "quarantin" in low or "finaliz" in low:
                    self.finished = True
                    return None
                found = re.search(r"expected (\d+)", body)
                if found:
                    self.step = int(found.group(1)) - 1
                    payload["step"] = self.step + 1
                    continue
                if "reuse" in low or "different action" in low:
                    self.step += 1
                    payload["step"] = self.step + 1
                    continue
                return None
            if status in (400, 401, 402, 403, 404, 422):
                if status == 402:
                    self.broke = True
                return None
        return None

